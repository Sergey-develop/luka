import { expect, test } from '@playwright/test'

test('Russian covers the full round, preserves input and progress, and persists after reload', async ({ page }, testInfo) => {
  test.setTimeout(60000)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: 'Переключить на русский', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'ru')
  await expect(page.locator('.language-switch button')).toHaveCount(1)
  await expect(page.locator('.language-switch img')).toHaveAttribute('src', /language-ru/)
  const toggle = (await page.locator('.language-switch').boundingBox())!
  const frame = (await page.locator('.kiosk').boundingBox())!
  expect(toggle.x + toggle.width).toBeLessThan(frame.x + frame.width / 2)
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Футбольный')
  await page.screenshot({ path: testInfo.outputPath('ru-idle.png') })
  await page.getByRole('button', { name: 'НАЧАТЬ ИГРУ', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Как играть' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('ru-rules.png') })
  await page.getByRole('button', { name: 'ПРОДОЛЖИТЬ', exact: true }).click()
  const uid = page.getByRole('textbox', { name: 'CoinW UID', exact: true })
  await uid.fill('bad')
  await expect(page.getByRole('alert')).toContainText('не более 20 цифр')
  await uid.fill('123456')
  await page.getByRole('button', { name: 'Switch to English', exact: true }).click()
  await expect(uid).toHaveValue('123456')
  await expect(page.getByRole('button', { name: 'START GAME', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Переключить на русский', exact: true }).click()
  await page.getByRole('button', { name: 'НАЧАТЬ ИГРУ', exact: true }).click()
  const ball = page.locator('.ball-control')
  await expect(ball).toBeEnabled({ timeout: 10000 })
  await expect(page.locator('.game-hud')).toContainText('ОЧКИ')
  await page.getByRole('button', { name: 'Switch to English', exact: true }).click()
  await expect(page.locator('.game-hud')).toContainText('POINTS')
  await expect(page.locator('.shot-counter')).toContainText('1/5')
  await expect(ball).toBeEnabled()
  await page.getByRole('button', { name: 'Переключить на русский', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('ru-game.png') })
  for (let i = 0; i < 5; i++) {
    await expect(ball).toBeEnabled()
    await ball.press('Enter')
    await expect(page.getByRole('status').getByText('СЕЙВ', { exact: true })).toBeVisible()
  }
  await expect(page.getByRole('heading', { name: 'Твой результат', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('ru-result.png') })
  await page.getByRole('button', { name: 'РЕЙТИНГ', exact: true }).click()
  await expect(page.getByRole('columnheader', { name: 'ИГРОК' })).toBeVisible()
  await expect(page.getByText('ТЫ', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('ru-leaderboard.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.reload()
  await expect(page.getByRole('button', { name: 'НАЧАТЬ ИГРУ', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Switch to English', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'START GAME', exact: true })).toBeVisible()
})

test('inactivity warning is translated into Russian', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.clock.install()
  await page.goto('/')
  await page.getByRole('button', { name: 'Переключить на русский', exact: true }).click()
  await page.getByRole('button', { name: 'НАЧАТЬ ИГРУ', exact: true }).click()
  await page.clock.fastForward(10200)
  await expect(page.getByRole('alertdialog')).toContainText('ПРОДОЛЖИМ?')
  await expect(page.getByRole('alertdialog')).toContainText('Возврат на главный экран через')
  await page.getByRole('alertdialog').getByRole('button', { name: 'ПРОДОЛЖИТЬ', exact: true }).click()
  await expect(page.getByRole('alertdialog')).toHaveCount(0)
})
